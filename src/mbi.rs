    #[test]
    fn produce_container_new() {
        let ecdsa_data = ECDSAXY
            .iter()
            .enumerate()
            .map(|(id, ec)| SrkData {
                srk_id: id as u8,
                data: Vec::from(*ec),
            })
            .collect::<Vec<_>>();

        let used = 2;

        let mut ecsda_crypto_params = ecdsa_data.iter().map(|ecsda_data| {
            let mut data = Cursor::new(Vec::new());
            ecsda_data.write(&mut data).expect("Failed to write");
            crate::original_code::srk_data_hash_64(&data.into_inner(), AHAB_HASH_SHA384)
                .expect("Failed to hash")
        });

        let srk_table_ecsda = SrkTableEcsdaP384 {
            records: array::from_fn(|_| SrkRecordEcsda {
                sign_algorithm: SignAlgorithm::Ecdsa,
                hash_algorithm: HashAlgorithm::Sha384,
                key_size: AHAB_KEY_SIZE_P384,
                p_len_x: ECC_P384_COORD_LEN as u16,
                p_len_y: ECC_P384_COORD_LEN as u16,
                crypto_params: Vec::from(ecsda_crypto_params.next().expect("Oops")),
            }),
        };

        let mldsa_data = MLDSARAW
            .iter()
            .enumerate()
            .map(|(id, ec)| SrkData {
                srk_id: id as u8,
                data: Vec::from(*ec),
            })
            .collect::<Vec<_>>();

        for entry in &mldsa_data {
            let data = entry.to_vec().unwrap();
            let check = original_code::srk_data_export(&entry.data, entry.srk_id).unwrap();
            assert_eq!(data, check);
        }

        let mut mldsa_params = mldsa_data.iter().map(|ecsda_data| {
            let mut data = Cursor::new(Vec::new());
            ecsda_data.write(&mut data).expect("Failed to write");
            (
                ecsda_data.data.len() as u16,
                crate::original_code::srk_data_hash_64(&data.into_inner(), AHAB_HASH_SHA384)
                    .expect("Failed to hash"),
            )
        });

        let srk_table_mldsa = SrkTableMldsa {
            records: array::from_fn(|_| {
                let (p_len, crypto_params) = mldsa_params.next().expect("Oops");
                SrkRecordMldsa {
                    sign_algorithm: SignAlgorithm::Mldsa,
                    hash_algorithm: HashAlgorithm::Sha384,
                    key_size: 0x09,
                    p_len,
                    crypto_params: Vec::from(crypto_params),
                }
            }),
        };

        let srk_array = SrkArrayHybrid {
            version: 0x0,
            len: 0xD00,
            tag: TAG_AHAB_SRK_ARRAY,
            count: 2,
            srk_table_ecsda,
            srk_data_ecdsa: ecdsa_data[used].clone(),
            srk_table_mldsa,
            srk_data_mldsa: mldsa_data[used].clone(),
        };

        let signature_block = SignatureBlock {
            version: AHAB_SIGBLK_VERSION,
            cert_off: 0x0,
            srk_off: 0x10,
            srk_array,
            signatures: [
                SignatureContainer {
                    signature: Vec::from([00; 0x64]),
                },
                SignatureContainer {
                    signature: Vec::from([00; 0x1217]),
                },
            ],
        };

        let orig = AhabContainer {
            version: AHAB_CONTAINER_VERSION,
            flags: AhabContainerFlags::new()
                .with_used_srk_id(used as u8)
                .with_srk_set(5),
            fuse_version: 6,
            image_version: 7,
            images: vec![ImageEntry {
                offset: 0x5,
                size: 0x50,
                load_address: 0x3,
                entry_point: 0x30,
                flags: 0x15,
                hash: [0xFF; 64],
            }],
            signature_block,
            tag: TAG_AHAB_CONTAINER_HEADER,
        };

        let mut res = Cursor::new(Vec::new());
        orig.write(&mut res).expect("Failed to write result");
        let res = res.into_inner();

        binary_compare(&res, KNOWN_GOOD);

        let roundtrip =
            AhabContainer::read(&mut Cursor::new(res)).expect("Failed to parse roundtrip");

        assert_eq!(roundtrip, orig)
    }
